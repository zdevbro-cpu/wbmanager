const tableWarnings = [];
const T = (rows, widths = null) => {
  const cols = rows[0].length;
  if (widths && widths.length !== cols) {
    tableWarnings.push(`열 ${cols}개인데 widths ${widths.length}개 — 첫 셀: ${rows[0][0]}`);
    widths = null;
  }
  if (rows.some((r) => r.length !== cols)) {
    tableWarnings.push(`행마다 셀 수가 다르다 — 첫 셀: ${rows[0][0]}`);
  }
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    layout: TableLayoutType.FIXED,
    columnWidths: widths ? widths.map((w) => Math.round((9360 * w) / 100)) : undefined,
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: 'B9C6D8' },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: 'B9C6D8' },
      left: { style: BorderStyle.SINGLE, size: 4, color: 'B9C6D8' },
      right: { style: BorderStyle.SINGLE, size: 4, color: 'B9C6D8' },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: 'D5DEE9' },
      insideVertical: { style: BorderStyle.SINGLE, size: 2, color: 'D5DEE9' },
    },
    rows: rows.map(
      (r, i) =>
        new TableRow({
          tableHeader: i === 0,
          children: r.map((c, j) =>
            cell(c, {
              bold: i === 0,
              shade: i === 0 ? GREY : null,
              width: widths ? widths[j] : Math.round(100 / r.length),
            }),
          ),
        }),
    ),
  });
};

