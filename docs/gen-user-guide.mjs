const EXTS = ['.png', '.jpg', '.jpeg'];
const shotStatus = [];
const MAX_W = 620;
const MAX_H = 430;

function shotFile(key) {
  for (const ext of EXTS) {
    const p = path.join(shotDir, key + ext);
    if (fs.existsSync(p)) return p;
  }
  return null;
}

function imageSize(buf) {
  if (buf.length > 24 && buf[0] === 0x89 && buf[1] === 0x50) {
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length - 9) {
      if (buf[i] !== 0xff) {
        i++;
        continue;
      }
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
        return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
      }
      i += 2 + len;
    }
  }
  return null;
}

function Shot(key, caption) {
  const file = shotFile(key);
  if (!file) {
    shotStatus.push(`[자리표시] ${key} — ${caption}`);
    return [
      boxed(
        [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 40, line: 300 },
            children: [new TextRun({ text: '[ 화면 캡처 위치 ]', font: FONT, size: 19, bold: true, color: '7A8CA3' })],
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 0, line: 300 },
            children: [new TextRun({ text: caption, font: FONT, size: 18, color: '7A8CA3' })],
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 0, line: 300 },
            children: [new TextRun({ text: `파일명: screenshots/${key}.png`, font: FONT, size: 17, color: '9AA8BB' })],
          }),
        ],
        { fill: 'F7F9FC', edge: 'C9D4E2', accent: 'A9BAD0' },
      ),
      Spacer(),
    ];
  }

  const data = fs.readFileSync(file);
  const size = imageSize(data) ?? { w: MAX_W, h: 400 };
  const scale = Math.min(MAX_W / size.w, MAX_H / size.h, 1);
  const w = Math.round(size.w * scale);
  const h = Math.round(size.h * scale);
  shotStatus.push(`[삽입] ${key} — ${path.basename(file)}`);

  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 60 },
      children: [
        new ImageRun({
          data,
          transformation: { width: w, height: h },
          type: path.extname(file).toLowerCase() === '.png' ? 'png' : 'jpg',
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 200 },
      children: [new TextRun({ text: `▲ ${caption}`, font: FONT, size: 17, color: '666666' })],
    }),
  ];
}

